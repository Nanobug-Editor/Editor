"""Compare snapshot and old-content-reference history models on identical traces.

These SQLite prototypes borrow data-model ideas from VS Code and IDEA. They do
not execute either editor, reproduce its VFS, or modify Nanobug product code.
The immutable corpus comes from benchmark_storage.py; all captured states are
verified for content, existence and path before and after garbage collection.
"""

from __future__ import annotations

import argparse
import ctypes
import json
import os
from pathlib import Path
import platform
import random
import sqlite3
import struct
import sys
import time

# Keep generated bytecode out of the research source directory.
sys.dont_write_bytecode = True
import benchmark_storage as common


# Snapshot/log layout and object encoding are separate experimental dimensions.
MODES = ("snapshot_raw", "snapshot_rawcas", "snapshot_lz4", "snapshot_zstd",
         "oldref_rawcas", "oldref_lz4", "oldref_zstd")
# Bits indicate which preimage fields a change can restore; they are not text patches.
KEY, PATH, ALIVE = 1, 2, 4


class Lz4:
    """Bind native fast LZ4 block encoding; persisted objects carry raw output size."""

    def __init__(self, dll: Path):
        """Load the experiment DLL at dll without installing a global library."""
        self.lib = ctypes.CDLL(str(dll))
        declarations = {
            "LZ4_versionString": (ctypes.c_char_p, []),
            "LZ4_compressBound": (ctypes.c_int, [ctypes.c_int]),
            "LZ4_compress_default": (ctypes.c_int,
                                     [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int, ctypes.c_int]),
            "LZ4_decompress_safe": (ctypes.c_int,
                                    [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int, ctypes.c_int]),
        }
        for name, (result, arguments) in declarations.items():
            function = getattr(self.lib, name)
            function.restype, function.argtypes = result, arguments

    def encode(self, contents: bytes) -> bytes:
        """Return a raw LZ4 block for contents, raising if the encoder fails."""
        capacity = self.lib.LZ4_compressBound(len(contents))
        output = ctypes.create_string_buffer(capacity)
        written = self.lib.LZ4_compress_default(contents, output, len(contents), capacity)
        if written <= 0:
            raise RuntimeError("LZ4 compression failed")
        return output.raw[:written]

    def decode(self, payload: bytes, size: int) -> bytes:
        """Restore payload to exactly size bytes, rejecting malformed data."""
        output = ctypes.create_string_buffer(size)
        written = self.lib.LZ4_decompress_safe(payload, output, len(payload), size)
        if written != size:
            raise RuntimeError("LZ4 reconstructed size changed")
        return output.raw[:written]


def make_trace(manifest: dict) -> list[dict]:
    """Interleave manifest versions and add rename/move/delete/restore captures per file."""
    records = {(record["file"], record["sequence"]): record for record in manifest["records"]}
    files = sorted({record["file"] for record in manifest["records"]})
    marks, paths, trace = {}, {}, []

    def capture(file_id: int, kind: str, record: dict | None, present: bool):
        """Append one post-operation state, retaining the immutable source record as oracle."""
        mark = marks.get(file_id, 0)
        trace.append({"id": len(trace) + 1, "file": file_id, "mark": mark,
                      "kind": kind, "record": record, "path": paths[file_id],
                      "present": present, "cohort": records[file_id, 0]["cohort"]})
        marks[file_id] = mark + 1

    for sequence in range(48):
        for file_id in files:
            paths.setdefault(file_id, f"src/file-{file_id}.rs")
            if sequence == 12:
                paths[file_id] = f"src/renamed-{file_id}.rs"
                capture(file_id, "rename", records[file_id, sequence - 1], True)
            elif sequence == 24:
                paths[file_id] = f"lib/renamed-{file_id}.rs"
                capture(file_id, "move", records[file_id, sequence - 1], True)
            elif sequence == 36:
                capture(file_id, "delete", None, False)
                # Explicit restore preserves this logical file identity; an unrelated
                # new file created at the same path is a separate product decision.
                capture(file_id, "restore", records[file_id, sequence - 1], True)
            capture(file_id, "create" if sequence == 0 else "write", records[file_id, sequence], True)
    return trace


class HistoryModel:
    """Store immutable complete content with either snapshot rows or old-reference events."""

    def __init__(self, db: sqlite3.Connection, mode: str, zstd: common.Zstd, lz4: Lz4):
        """Create fresh tables in db; mode selects layout/encoding and native codecs do compression."""
        self.db, self.mode, self.zstd, self.lz4 = db, mode, zstd, lz4
        self.log = mode.startswith("oldref")
        # Only the writer caches identity metadata; measured readers always query the database.
        self.heads, self.known = {}, set()
        db.executescript("""
            CREATE TABLE objects(id BLOB PRIMARY KEY, encoding TEXT NOT NULL,
                raw_size INTEGER NOT NULL, payload BLOB NOT NULL);
            CREATE TABLE heads(file INTEGER PRIMARY KEY, path TEXT, object_id BLOB, alive INTEGER);
            CREATE TABLE versions(file INTEGER, mark INTEGER, event_id INTEGER, kind TEXT,
                PRIMARY KEY(file,mark)) WITHOUT ROWID;
        """)
        if self.log:
            db.executescript("""
                CREATE TABLE changes(id INTEGER PRIMARY KEY, file INTEGER, kind TEXT, mask INTEGER,
                    old_path TEXT, old_key BLOB, old_alive INTEGER);
                CREATE INDEX changes_by_file ON changes(file,id);
                CREATE INDEX changes_key ON changes(file,id) WHERE (mask & 1)!=0;
                CREATE INDEX changes_path ON changes(file,id) WHERE (mask & 2)!=0;
                CREATE INDEX changes_alive ON changes(file,id) WHERE (mask & 4)!=0;
            """)
        else:
            db.execute("CREATE TABLE snapshots(file INTEGER, mark INTEGER, path TEXT, object_id BLOB, "
                       "alive INTEGER, PRIMARY KEY(file,mark)) WITHOUT ROWID")

    def put_object(self, contents: bytes, checksum: bytes, event: dict) -> bytes:
        """Persist contents under checksum/CAS or unique event identity; return its object key."""
        key = checksum if self.mode != "snapshot_raw" else common.digest(
            checksum + struct.pack("<II", event["file"], event["mark"]))
        if key not in self.known:
            if self.mode.endswith("zstd"):
                encoding, payload = "zstd", self.zstd.encode(contents, 1)
            elif self.mode.endswith("lz4") and len(contents) > 8000:
                encoding, payload = "lz4", self.lz4.encode(contents)
            else:
                encoding, payload = "raw", contents
            self.db.execute("INSERT INTO objects VALUES(?,?,?,?)", (key, encoding, len(contents), payload))
            self.known.add(key)
        return key

    def capture(self, event: dict, contents: bytes | None):
        """Commit event's post-state; contents is immutable input for create/write/restore only."""
        file_id = event["file"]
        before = self.heads.get(file_id, (None, None, 0, None))
        path, key, alive, checksum = before
        if not event["present"]:
            key, checksum = None, None
        elif contents is not None:
            checksum = common.digest(contents)
            if not alive or checksum != before[3]:
                key = self.put_object(contents, checksum, event)
        after = event["path"], key, int(event["present"]), checksum
        mask = (KEY if before[1] != after[1] else 0) | (PATH if before[0] != after[0] else 0)
        mask |= ALIVE if before[2] != after[2] else 0
        if self.log and mask:
            self.db.execute("INSERT INTO changes VALUES(?,?,?,?,?,?,?)",
                            (event["id"], file_id, event["kind"], mask, before[0], before[1], before[2]))
        if not self.log:
            self.db.execute("INSERT INTO snapshots VALUES(?,?,?,?,?)",
                            (file_id, event["mark"], after[0], after[1], after[2]))
        if mask:
            self.db.execute("INSERT INTO heads VALUES(?,?,?,?) ON CONFLICT(file) DO UPDATE SET "
                            "path=excluded.path,object_id=excluded.object_id,alive=excluded.alive",
                            (file_id, after[0], after[1], after[2]))
        self.db.execute("INSERT INTO versions VALUES(?,?,?,?)",
                        (file_id, event["mark"], event["id"], event["kind"]))
        self.db.commit()
        self.heads[file_id] = after

    def state(self, file_id: int, mark: int, strategy: str) -> tuple:
        """Resolve file/mark to path, object key and existence using replay or indexed jump."""
        if not self.log:
            return self.db.execute("SELECT path,object_id,alive FROM snapshots WHERE file=? AND mark=?",
                                   (file_id, mark)).fetchone()
        event_id = self.db.execute("SELECT event_id FROM versions WHERE file=? AND mark=?",
                                   (file_id, mark)).fetchone()[0]
        result = list(self.db.execute("SELECT path,object_id,alive FROM heads WHERE file=?", (file_id,)).fetchone())
        if strategy == "replay":
            for mask, path, key, alive in self.db.execute(
                    "SELECT mask,old_path,old_key,old_alive FROM changes WHERE file=? AND id>? ORDER BY id DESC",
                    (file_id, event_id)):
                if mask & PATH:
                    result[0] = path
                if mask & KEY:
                    result[1] = key
                if mask & ALIVE:
                    result[2] = alive
        else:
            # The first future field-changing event carries the field's exact value
            # after the requested capture. This skips metadata replay, not text decoding.
            for field, bit, position in (("old_path", PATH, 0), ("old_key", KEY, 1), ("old_alive", ALIVE, 2)):
                row = self.db.execute(f"SELECT {field} FROM changes WHERE file=? AND id>? AND "
                                      f"(mask & {bit})!=0 ORDER BY id LIMIT 1", (file_id, event_id)).fetchone()
                if row:
                    result[position] = row[0]
        return tuple(result)

    def read(self, file_id: int, mark: int, strategy: str = "replay") -> tuple:
        """Return a complete historical state; decode only the final referenced content object."""
        path, key, alive = self.state(file_id, mark, strategy)
        if not alive:
            if key is not None:
                raise AssertionError("absent file retained a live content reference")
            return path, False, None
        encoding, size, payload = self.db.execute(
            "SELECT encoding,raw_size,payload FROM objects WHERE id=?", (key,)).fetchone()
        contents = payload if encoding == "raw" else (
            self.lz4.decode(payload, size) if encoding == "lz4" else self.zstd.decode(payload, size))
        return path, True, contents

    def collect(self) -> dict:
        """Retain each file's newest half of captures and reclaim unreachable complete objects."""
        started = time.perf_counter_ns()
        for file_id, count in self.db.execute("SELECT file,COUNT(*) FROM versions GROUP BY file").fetchall():
            self.db.execute("DELETE FROM versions WHERE file=? AND mark<?", (file_id, count // 2))
            if self.log:
                boundary = self.db.execute("SELECT MIN(event_id) FROM versions WHERE file=?", (file_id,)).fetchone()[0]
                # Reconstructing the first retained post-state only needs later preimages.
                self.db.execute("DELETE FROM changes WHERE file=? AND id<=?", (file_id, boundary))
            else:
                self.db.execute("DELETE FROM snapshots WHERE file=? AND mark<?", (file_id, count // 2))
        roots = {row[0] for row in self.db.execute("SELECT object_id FROM heads WHERE object_id IS NOT NULL")}
        query = "SELECT old_key FROM changes WHERE old_key IS NOT NULL AND (mask & 1)!=0" if self.log else (
            "SELECT object_id FROM snapshots WHERE object_id IS NOT NULL")
        roots.update(row[0] for row in self.db.execute(query))
        obsolete = [(row[0],) for row in self.db.execute("SELECT id FROM objects") if row[0] not in roots]
        self.db.executemany("DELETE FROM objects WHERE id=?", obsolete)
        self.db.commit()
        self.db.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        self.db.execute("VACUUM")
        self.db.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        return {"total_ms": (time.perf_counter_ns() - started) / 1e6,
                "deleted_objects": len(obsolete), "remaining_objects": len(roots)}


def verify(model: HistoryModel, trace: list[dict], strategy: str):
    """Require every trace post-state's original path, existence and content hash."""
    for event in trace:
        path, present, contents = model.read(event["file"], event["mark"], strategy)
        if path != event["path"] or present != event["present"]:
            raise AssertionError(f"structural state mismatch at capture {event['id']}")
        if present and common.digest(contents).hex() != event["record"]["sha256"]:
            raise AssertionError(f"content mismatch at capture {event['id']}")


def run_model(mode: str, repeat: int, scratch: Path, trace: list[dict], corpus: bytes,
              zstd: common.Zstd, lz4: Lz4) -> dict:
    """Measure mode's durable writes, warm random reads and collection in a fresh repeat database."""
    path = scratch / f"{mode}-{repeat}.sqlite"
    model = HistoryModel(common.connect(path), mode, zstd, lz4)
    writes, structures = [], []
    cpu_started = time.process_time_ns()
    for event in trace:
        record = event["record"]
        contents = corpus[record["offset"]:record["offset"] + record["size"]] if (
            record is not None and event["kind"] in ("write", "create", "restore")) else None
        started = time.perf_counter_ns()
        model.capture(event, contents)
        sample = {"ms": (time.perf_counter_ns() - started) / 1e6, "kind": event["kind"],
                  "cohort": event["cohort"]}
        (writes if event["kind"] in ("write", "create") else structures).append(sample)
    write_cpu_ms = (time.process_time_ns() - cpu_started) / 1e6
    model.db.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    stored_bytes = path.stat().st_size
    object_count = model.db.execute("SELECT COUNT(*) FROM objects").fetchone()[0]
    model.db.close()
    # Reopen without writer caches: correctness and measured queries must use persisted records.
    model.db = common.connect(path)
    strategies = ("replay", "jump") if model.log else ("direct",)
    for strategy in strategies:
        verify(model, trace, strategy)
    reads, lists = {}, []
    for strategy in strategies:
        samples = []
        order = list(trace)
        random.Random(common.SEED + repeat).shuffle(order)
        for event in order:
            started = time.perf_counter_ns()
            model.read(event["file"], event["mark"], strategy)
            samples.append({"ms": (time.perf_counter_ns() - started) / 1e6,
                            "cohort": event["cohort"], "kind": event["kind"]})
        reads[strategy] = {"summary": common.summary([sample["ms"] for sample in samples]), "samples": samples}
    for event in trace:
        started = time.perf_counter_ns()
        rows = model.db.execute("SELECT mark,event_id,kind FROM versions WHERE file=? ORDER BY mark DESC LIMIT 50",
                                (event["file"],)).fetchall()
        lists.append((time.perf_counter_ns() - started) / 1e6)
        if len(rows) != 50:
            raise AssertionError("version index lost captures")
    gc = model.collect()
    retained = [event for event in trace if event["mark"] >= 26]
    for strategy in strategies:
        verify(model, retained, strategy)
    dangling = model.db.execute("SELECT COUNT(*) FROM heads WHERE object_id IS NOT NULL AND object_id NOT IN "
                               "(SELECT id FROM objects)").fetchone()[0]
    if dangling or model.db.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
        raise AssertionError("garbage collection damaged the database")
    model.db.close()
    return {"mode": mode, "repeat": repeat, "database_bytes": stored_bytes,
            "after_gc_bytes": path.stat().st_size, "object_count": object_count,
            "write_cpu_ms": write_cpu_ms, "gc": gc,
            "writes": {"summary": common.summary([sample["ms"] for sample in writes]), "samples": writes},
            "structures": {"summary": common.summary([sample["ms"] for sample in structures]), "samples": structures},
            "reads": reads, "lists": {"summary": common.summary(lists), "samples_ms": lists}}


def main():
    """Run isolated comparisons from CLI paths and persist original results after each completed group."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, required=True)
    parser.add_argument("--scratch", type=Path, required=True)
    parser.add_argument("--zstd-dll", type=Path, required=True)
    parser.add_argument("--lz4-dll", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--repeats", type=int, default=3)
    args = parser.parse_args()
    args.scratch.mkdir(parents=True, exist_ok=False)
    manifest = json.loads((args.corpus / "corpus.json").read_text(encoding="utf-8"))
    corpus = (args.corpus / "corpus.bin").read_bytes()
    if common.digest(corpus).hex() != manifest["corpus_sha256"]:
        raise AssertionError("immutable input corpus changed")
    trace = make_trace(manifest)
    zstd, lz4 = common.Zstd(args.zstd_dll), Lz4(args.lz4_dll)
    report = {"environment": {"python": sys.version, "platform": platform.platform(),
              "cpu": os.environ.get("PROCESSOR_IDENTIFIER"), "cores": os.cpu_count(),
              "sqlite": sqlite3.sqlite_version, "zstd": zstd.lib.ZSTD_versionString().decode(),
              "lz4": lz4.lib.LZ4_versionString().decode(), "lz4_dll": str(args.lz4_dll)},
              "corpus_sha256": manifest["corpus_sha256"], "corpus_directory": str(args.corpus),
              "scratch": str(args.scratch), "captures": len(trace),
              "source_versions": len(manifest["records"]), "runs": []}
    (args.scratch / "trace.json").write_text(json.dumps(trace, indent=2), encoding="utf-8")
    try:
        for repeat in range(args.repeats):
            modes = list(MODES)
            random.Random(common.SEED + repeat).shuffle(modes)
            for mode in modes:
                result = run_model(mode, repeat, args.scratch, trace, corpus, zstd, lz4)
                report["runs"].append(result)
                args.report.write_text(json.dumps(report, indent=2), encoding="utf-8")
                print(json.dumps({"mode": mode, "repeat": repeat, "bytes": result["database_bytes"],
                                  "write": result["writes"]["summary"], "gc": result["gc"],
                                  "reads": {key: value["summary"] for key, value in result["reads"].items()}}), flush=True)
    finally:
        zstd.close()


if __name__ == "__main__":
    main()
